    // MARK: - Helpers

    public static string WindowClassName(IntPtr hwnd)
    {
        var builder = new StringBuilder(256);
        return GetClassName(hwnd, builder, builder.Capacity) > 0 ? builder.ToString() : "";
    }

    public static string WindowTitle(IntPtr hwnd)
    {
        var builder = new StringBuilder(512);
        return GetWindowText(hwnd, builder, builder.Capacity) > 0 ? builder.ToString() : "";
    }

    public static string? ProcessImagePath(uint processId)
    {
        var handle = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, processId);
        if (handle == IntPtr.Zero) return null;
        try
        {
            var builder = new StringBuilder(1024);
            var size = builder.Capacity;
            return QueryFullProcessImageName(handle, 0, builder, ref size) ? builder.ToString(0, size) : null;
        }
        finally
        {
            CloseHandle(handle);
        }
    }

